        + A(7)*A(8)*A(9)*A(10)*(U(1)+A(1)*U(2)*U(5)+A(1)*A(2)*U(3)*U(5)*U(6)+A(1)*A(2)*A(3)*U(4)*U(5)*U(6))...
        + A(2)*A(3)*A(4)*A(5)*A(7)*A(8)*U(1)*(U(9)+A(9)*U(10))...
        + U(1)*A(3)*A(4)*A(6)*A(7)*A(8)*A(9)*U(10)*(U(2)+A(2)*U(5)) + A(1)*U(2)*A(3)*A(4)*A(6)*A(7)*A(8)*A(9)*U(10)...
        + A(1)*U(2)*A(3)*A(4)*A(5)*A(6)*A(9)*U(10)*(U(7)+A(7)*U(8)) + U(1)*A(2)*A(5)*A(6)*A(7)*A(8)*U(9)*A(10)*(U(3)+A(3)*U(4));
end
